/**
 * Regenerates src/features/home/brochure/tracking.ts.
 *
 * The brochure PDF was set in a cut of Montserrat whose glyph advances differ
 * slightly from the webfont Google serves, so runs drift by up to ~3.5% in
 * width. brochure-pdf-widths.json holds each run's advance width taken straight
 * out of the PDF (normalised to em, so it is font-size independent); this script
 * measures the same run in a real browser and emits the letter-spacing that
 * restores the PDF's width exactly.
 *
 * Usage:  npm run dev        (in another shell)
 *         node scripts/brochure-tracking.mjs [url]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { chromium } from 'playwright';

const here = path.dirname(fileURLToPath(import.meta.url));
const URL = process.argv[2] ?? 'http://localhost:5173/brochure';
const WIDTHS = JSON.parse(fs.readFileSync(path.join(here, 'brochure-pdf-widths.json'), 'utf8'));
const OUT = path.join(here, '..', 'src', 'features', 'home', 'brochure', 'tracking.ts');

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1191, height: 900 } });
await page.goto(URL, { waitUntil: 'networkidle' });
await page.evaluate(() => document.fonts.ready);
await page.waitForTimeout(500);

const tracking = await page.evaluate((widths) => {
  const probe = document.createElement('span');
  probe.style.cssText = 'position:absolute;visibility:hidden;white-space:pre;font-family:Montserrat;font-size:200px';
  document.body.appendChild(probe);

  /** Width of `text` at 200px, in em. */
  const measure = (text, weight, letterSpacing) => {
    probe.style.fontWeight = String(weight);
    probe.style.letterSpacing = letterSpacing;
    probe.textContent = text;
    return probe.getBoundingClientRect().width / 200;
  };

  const out = {};
  for (const [key, target] of Object.entries(widths)) {
    const sep = key.indexOf('|');
    const weight = Number(key.slice(0, sep));
    const text = key.slice(sep + 1);
    if (!text.length) continue;

    // letter-spacing adds one step after every character, so one linear solve
    // lands on the target; a second pass absorbs sub-pixel rounding.
    let track = 0;
    for (let pass = 0; pass < 2; pass++) {
      const got = measure(text, weight, `${track}em`);
      track += (target - got) / text.length;
    }
    track = Math.round(track * 1e5) / 1e5;
    if (track !== 0) out[key] = track;
  }
  probe.remove();
  return out;
}, WIDTHS);

const body = Object.entries(tracking)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`)
  .join('\n');

fs.writeFileSync(
  OUT,
  `/**\n * Per-run tracking corrections, in em, that restore the advance widths the\n * brochure PDF uses. Generated by \`node scripts/brochure-tracking.mjs\` —\n * do not edit by hand.\n */\nexport const TRACKING: Record<string, number> = {\n${body}\n};\n`,
);
console.log(`wrote ${Object.keys(tracking).length} corrections to ${path.relative(process.cwd(), OUT)}`);

await browser.close();
