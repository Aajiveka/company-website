/**
 * Institution / university master for India.
 *
 * The legacy schema has no institution table at all — "Institution / University name" was a
 * free-text box, so the same university arrived spelled six ways and nothing could be filtered
 * or counted on it. This file is the seed for `tblMstrInstitute`.
 *
 * Provenance: every row is a real, recognised institution — UGC-listed universities (central,
 * state, deemed and private), the Institutes of National Importance (IITs, NITs, IIITs, IIMs,
 * AIIMS, IISc, ISI), the National Law Universities, the state agricultural and health-sciences
 * universities, and well-known affiliated colleges. Nothing here is invented to pad a dropdown.
 * Coverage is deliberately broadest where candidate volume is (UP, Bihar, Maharashtra,
 * Tamil Nadu, Karnataka…) and thinner for the small union territories, which have only a
 * handful of higher-education institutions between them.
 *
 * The list is a starting point, never a gate: the Education step lets a candidate type any
 * institution, and an unmatched name is saved verbatim. Adding rows here only improves the
 * suggestions.
 *
 * `state` matches tblMstrState.Descr exactly. `city` is the city as it is commonly written; the
 * loader resolves it to a tblMstrCily row when the district name matches and leaves CityID NULL
 * otherwise, because the city master is a *district* list and many institutions sit in a city
 * whose district carries a different name (Bhubaneswar in Khordha, Roorkee in Haridwar).
 */

